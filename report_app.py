import streamlit as st
import os

# --- Page Configuration ---
st.set_page_config(
    page_title="Market Intelligence Hub",
    page_icon="📊",
    layout="wide"
)

st.title("📊 NSE Futures & Strategy Market Intelligence Hub")
st.markdown("Live dashboard displaying automated market reports generated by your GitHub Actions pipeline.")

# --- Define Report Files ---
reports = {
    "⚡ Active Stocks": "active_stocks_report.txt",
    "🔍 RVOL Active Signals": "rvol_active_signals_report.txt",
    "📈 Bullish Report": "bullish_report.txt",
    "📉 Bearish Report": "bearish_report.txt",
    "🎯 Consolidated Report": "consolidated_strategy_report.txt"
}

# --- Create Navigation Tabs ---
tabs = st.tabs(list(reports.keys()))

def load_report_text(filename):
    """Safely loads text report files if they exist."""
    if os.path.exists(filename):
        with open(filename, "r", encoding="utf-8") as f:
            return f.read()
    return f"⚠️ Report file '{filename}' not found yet. Run your GitHub Actions pipeline to populate this report."

# --- Render Content in Each Tab ---
for tab, (report_name, filename) in zip(tabs, reports.items()):
    with tab:
        st.subheader(report_name)
        report_content = load_report_text(filename)
        # Using st.code preserves table spacing and column alignments nicely
        st.code(report_content, language="text")
