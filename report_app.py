import streamlit as st
import os
import requests

# --- Page Configuration ---
st.set_page_config(
    page_title="Market Intelligence Hub",
    page_icon="📊",
    layout="wide"
)

st.title("📊 NSE Futures & Strategy Market Intelligence Hub")
st.markdown("Live dashboard displaying automated market reports generated by your GitHub Actions pipeline.")

# --- Define Report Files ---
reports = {
    "⚡ Active Stocks": "active_stocks_report.txt",
    "🔍 RVOL Active Signals": "rvol_active_signals_report.txt",
    "🎯 Consolidated Report": "consolidated_strategy_report.txt",
    "📈 Bullish Report": "bullish_report.txt",
    "📉 Bearish Report": "bearish_report.txt"
}

# --- Workflow Trigger Function ---
def trigger_github_workflow():
    try:
        token = st.secrets["GITHUB_TOKEN"]
        owner = "SHANKARNBHAT"
        repo = "Reports-Messenger"
    except Exception:
        st.sidebar.error("⚠️ GITHUB_TOKEN is not configured in Streamlit secrets.")
        return False
    url = f"https://api.github.com/repos/{owner}/{repo}/actions/workflows/pipeline.yml/dispatches"
    
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28"
    }
    
    payload = {
        "ref": "main"  # Adjust if your default branch is 'master'
    }
    
    response = requests.post(url, json=payload, headers=headers)
    
    if response.status_code == 204:
        return True
    else:
        st.sidebar.error(f"Failed to trigger workflow: {response.text}")
        return False

# --- Sidebar Controls ---
st.sidebar.header("⚙️ Pipeline Controls")
st.sidebar.markdown("If the daily batch hasn't run, you can manually trigger the workflow here:")
if st.sidebar.button("🚀 Run Workflow Now"):
    with st.spinner("Triggering GitHub Actions workflow..."):
        success = trigger_github_workflow()
        if success:
            st.sidebar.success("Workflow triggered successfully! Refresh the page in a minute to see updated reports.")

st.sidebar.divider()
st.sidebar.markdown("Reports load automatically from the latest saved state.")

# --- Create Navigation Tabs ---
tabs = st.tabs(list(reports.keys()))

def load_report_text(filename):
    """Safely loads existing text report files by default."""
    if os.path.exists(filename):
        with open(filename, "r", encoding="utf-8") as f:
            return f.read()
    return f"⚠️ Report file '{filename}' not found yet. Click 'Run Workflow Now' in the sidebar to populate this report."

# --- Render Content in Each Tab ---
for tab, (report_name, filename) in zip(tabs, reports.items()):
    with tab:
        st.subheader(report_name)
        report_content = load_report_text(filename)
        # Using st.code preserves table spacing and column alignments nicely
        st.code(report_content, language="text")
